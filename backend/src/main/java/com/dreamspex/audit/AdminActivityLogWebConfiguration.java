package com.dreamspex.audit;

import org.springframework.context.annotation.Configuration;
import org.springframework.web.servlet.config.annotation.InterceptorRegistry;
import org.springframework.web.servlet.config.annotation.WebMvcConfigurer;

@Configuration
public class AdminActivityLogWebConfiguration implements WebMvcConfigurer {
    private final AdminActivityLogInterceptor interceptor;

    public AdminActivityLogWebConfiguration(AdminActivityLogInterceptor interceptor) {
        this.interceptor = interceptor;
    }

    @Override
    public void addInterceptors(InterceptorRegistry registry) {
        registry.addInterceptor(interceptor);
    }
}
