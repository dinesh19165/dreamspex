CREATE TABLE product_reviews (
    id VARCHAR(255) NOT NULL PRIMARY KEY,
    customer_id VARCHAR(255) NOT NULL,
    order_id VARCHAR(255) NOT NULL,
    product_id VARCHAR(255) NOT NULL,
    rating INT NOT NULL,
    title VARCHAR(120) NOT NULL,
    content TEXT NOT NULL,
    image_urls_json TEXT NULL,
    moderation_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    moderated_by VARCHAR(255) NULL,
    moderated_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_product_reviews_purchase UNIQUE (customer_id, order_id, product_id),
    CONSTRAINT ck_product_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_product_reviews_status CHECK (moderation_status IN ('PENDING', 'APPROVED', 'HIDDEN', 'REJECTED')),
    CONSTRAINT fk_product_reviews_customer FOREIGN KEY (customer_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_reviews_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_reviews_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_reviews_moderator FOREIGN KEY (moderated_by) REFERENCES users(id) ON DELETE SET NULL,
    KEY ix_product_reviews_product_status_rating (product_id, moderation_status, rating),
    KEY ix_product_reviews_customer_created (customer_id, created_at),
    KEY ix_product_reviews_order (order_id),
    KEY ix_product_reviews_status_created (moderation_status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
