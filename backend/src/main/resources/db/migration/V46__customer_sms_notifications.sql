CREATE TABLE customer_sms_notifications (
    id VARCHAR(255) NOT NULL PRIMARY KEY,
    event_key VARCHAR(160) NOT NULL,
    user_id VARCHAR(255) NOT NULL,
    order_id VARCHAR(255) NOT NULL,
    order_number VARCHAR(40) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    template_id VARCHAR(120) NULL,
    template_variables_encrypted TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    provider_message_id VARCHAR(160) NULL,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NOT NULL,
    expires_at DATETIME(6) NULL,
    last_error VARCHAR(500) NULL,
    sent_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT uk_customer_sms_event_key UNIQUE (event_key),
    CONSTRAINT ck_customer_sms_status CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'FAILED')),
    CONSTRAINT fk_customer_sms_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_customer_sms_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    KEY ix_customer_sms_status_retry (status, next_attempt_at),
    KEY ix_customer_sms_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
