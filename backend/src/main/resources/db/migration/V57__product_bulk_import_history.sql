CREATE TABLE product_import_jobs (
    id CHAR(36) NOT NULL PRIMARY KEY,
    created_by CHAR(36) NOT NULL,
    import_mode VARCHAR(16) NOT NULL,
    inventory_mode VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    workbook_name VARCHAR(255) NOT NULL,
    workbook_sha256 CHAR(64) NOT NULL,
    images_sha256 CHAR(64) NULL,
    total_rows INT UNSIGNED NOT NULL DEFAULT 0,
    new_products INT UNSIGNED NOT NULL DEFAULT 0,
    existing_products INT UNSIGNED NOT NULL DEFAULT 0,
    valid_records INT UNSIGNED NOT NULL DEFAULT 0,
    invalid_records INT UNSIGNED NOT NULL DEFAULT 0,
    missing_images INT UNSIGNED NOT NULL DEFAULT 0,
    duplicate_skus INT UNSIGNED NOT NULL DEFAULT 0,
    invalid_categories INT UNSIGNED NOT NULL DEFAULT 0,
    invalid_prices INT UNSIGNED NOT NULL DEFAULT 0,
    invalid_variants INT UNSIGNED NOT NULL DEFAULT 0,
    imported_records INT UNSIGNED NOT NULL DEFAULT 0,
    error_report_json LONGTEXT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    completed_at DATETIME(6) NULL,
    KEY ix_product_import_jobs_created (created_at),
    KEY ix_product_import_jobs_actor_created (created_by, created_at),
    CONSTRAINT fk_product_import_jobs_user FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_product_import_jobs_mode CHECK (import_mode IN ('CREATE', 'UPDATE')),
    CONSTRAINT ck_product_import_jobs_inventory_mode CHECK (inventory_mode IN ('SET', 'ADD')),
    CONSTRAINT ck_product_import_jobs_status CHECK (status IN ('PREVIEWED', 'COMPLETED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
